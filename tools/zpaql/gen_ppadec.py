#!/usr/bin/env python3
"""Builds the ZPAQL decoder of PPA's zpaq-std codec (pas/plugin/).

    gen_ppadec.py [--check]

pas/plugin/zpaql/model.zl (without its test main: everything from the line
MAIN_MARK on is left out), deflate.zl and ppadec.zl, in that order, compiled
with zpaqlc's opt=3 into pas/plugin/ppa1zpaql.inc: the config as Pascal
string constants (comp 0 0 $3 $4 0: H 2^$3 words and M 2^$4 bytes, both
from the codec's query), the words of H the program takes for its arrays,
tables and variables (the query adds what each stream needs: ppadec.zl's
header), and the program's record sizes.

The PCOMP must stay within ZPAQL's 65535 bytes (checked here).

With --check nothing is written: it fails if the .inc is not what the
sources make now (the suite runs this)."""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
PAS = os.path.join(REPO, 'pas')
ZL = os.path.join(PAS, 'plugin', 'zpaql')
INC = os.path.join(PAS, 'plugin', 'ppa1zpaql.inc')
sys.path.insert(0, HERE)
import zpaqlc

NAME = 'ppa1'
PH, PM = '$3', '$4'
MAIN_MARK = '# ---------------------------------------------------------------- the test main'
FILES = ('model.zl', 'deflate.zl', 'ppadec.zl')


def zl_consts(src):
    """NAME = <integer> at the top level of a .zl source"""
    return {m.group(1): int(m.group(2)) for m in re.finditer(r'^([A-Z][A-Z0-9_]*) = (-?\d+)\s*(?:#.*)?$', src, re.M)}


def source():
    """the decoder's whole source, as compiled"""
    parts = []
    for f in FILES:
        s = open(os.path.join(ZL, f)).read()
        if f == 'model.zl':
            if s.count(MAIN_MARK) != 1:
                raise SystemExit('gen_ppadec: model.zl has no single test-main marker')
            s = s[:s.index(MAIN_MARK)]
        parts.append(s)
    return '\n'.join(parts) + '\n'


def chunked(cfg):
    lines = [l.strip() for l in cfg.split('\n') if l.strip()]
    chunks, cur = [], ''
    for l in lines:
        if len(cur) + len(l) + 1 > 200:
            chunks.append(cur)
            cur = l
        else:
            cur = cur + ' ' + l if cur else l
    if cur:
        chunks.append(cur)
    return ' +\n'.join("    '" + ch.replace("'", "''") + "'#10" for ch in chunks) + ';'


def compile_decoder():
    src = source()
    cfg, size, c = zpaqlc.compile_source(src, NAME, PH, PM, opt=3)
    return src, cfg, size, c


def make_inc():
    src, cfg, size, c = compile_decoder()
    if size > 65535:
        raise SystemExit('gen_ppadec: %d bytes of PCOMP, past ZPAQL\'s 65535' % size)
    k = zl_consts(src)
    inc = ['{ Generated by tools/zpaql/gen_ppadec.py from pas/plugin/zpaql/model.zl,',
           '  deflate.zl and ppadec.zl: do not edit. The decoder of PPA\'s stream',
           '  (version %d, every image stream of the static model, the other streams' % k['SVER'],
           '  kept as bytes), compiled with zpaqlc\'s opt=3, %d bytes of PCOMP.' % size,
           '  Its config is comp 0 0 $3 $4 0: H 2^$3 words and M 2^$4 bytes, both',
           '  from the codec\'s query (what each stream needs: ppadec.zl\'s header). }',
           'const',
           '  { the words of H the decoder takes for its arrays, tables and variables }',
           '  PPA1_ZPAQL_STATIC_WORDS = %d;' % c.hwords,
           '  { the words of H it takes per chunk, per image or byte stream, per',
           '    substream (its records) }',
           '  PPA1_ZPAQL_CHUNK_WORDS = %d;' % k['CHUNKREC'],
           '  PPA1_ZPAQL_STREAM_WORDS = %d;' % k['STREAMREC'],
           '  PPA1_ZPAQL_SUB_WORDS = 2;',
           '  { the stream version it reads }',
           '  PPA1_ZPAQL_STREAM_VERSION = %d;' % k['SVER'],
           '  PPA1_ZPAQL_PCOMP_BYTES = %d;' % size,
           '  PPA1_ZPAQL: AnsiString =', chunked(cfg)]
    return '\n'.join(inc) + '\n', size, c


def config_of_inc(text):
    """the config back from the .inc's string constants"""
    part = text[text.index('  PPA1_ZPAQL: AnsiString ='):]
    part = part[:part.index(';\n')]
    return '\n'.join(m.replace("''", "'") for m in re.findall(r"^\s+'(.*)'#10", part, re.M)) + '\n'


def main():
    check = '--check' in sys.argv[1:]
    inc, size, c = make_inc()
    if check:
        if not os.path.exists(INC) or open(INC).read() != inc:
            print('gen_ppadec: not up to date: %s' % os.path.relpath(INC, REPO))
            sys.exit(1)
        print('ZPAQL decoder up to date: %s, %d bytes of PCOMP, %d static words of H'
              % (os.path.relpath(INC, REPO), size, c.hwords))
        return
    open(INC, 'w').write(inc)
    print('%s: %d bytes of PCOMP, %d static words of H' % (os.path.relpath(INC, REPO), size, c.hwords))


if __name__ == '__main__':
    main()
